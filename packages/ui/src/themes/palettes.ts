/** The palette with this id for the theme, or the theme's own colours. */
export function paletteOf(theme: ThemeId, id: string | null | undefined): Palette {
  const list = PALETTES[theme];
  return list.find((p) => p.id === id) ?? list[0]!;
}

/** The theme's tokens with a palette's colours swapped in ("custom" = your own colours, when made). */
export function withPalette(t: ThemeTokens, id: string | null | undefined, custom?: CustomColors | null): ThemeTokens {
  const palette = id === CUSTOM_ID && custom ? customPalette(t.id, custom) : paletteOf(t.id, id);
  return { ...t, colors: { ...t.colors, ...palette.colors } };
}
